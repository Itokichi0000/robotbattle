/**
 * Balance report for the 8-minute raid: runs the deterministic engine with
 * simulated crews of different sizes, role mixes and skill, and writes
 * docs/BALANCE_REPORT.md. Bots use the same solver as the demo bots.
 *
 *   pnpm simulate            # full report (a few minutes)
 *   pnpm simulate --quick    # fewer seeds
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_GAME_CONFIG, configHash } from '@sats-wars/shared';
import { type Aggregate, type RoleMix, aggregate, simulateRaid } from './simulate';

const quick = process.argv.includes('--quick');
const SEEDS = quick ? 6 : 30;
const pct = (x: number) => `${Math.round(x * 100)}%`;
const n1 = (x: number | null) => (x === null ? '—' : x.toFixed(1));

function run(pilots: number, mix: RoleMix, skill: number): Aggregate {
  return aggregate(
    Array.from({ length: SEEDS }, (_, i) =>
      simulateRaid({ pilots, mix, skill, seed: 1000 + i * 7919 + pilots * 31 }),
    ),
  );
}

const row = (label: string, a: Aggregate) =>
  `| ${label} | ${pct(a.winRate)} | ${pct(a.citiesLostRate)} | ${pct(a.timeoutRate)} | ${n1(a.survivingMean)} | ${pct(a.bossLeftMean)} | ${a.clearMean === null ? '—' : `${Math.round(a.clearMean)}s`} | ${Math.round(a.scoreMean)} | ${Math.round(a.syncMean)} | ${pct(a.specialActivated)}/${pct(a.specialFallback)}/${pct(a.specialFailed)} | ${Math.round(a.assistMean)} | ${Math.round(a.cityDamageMean)} / ${Math.round(a.shieldAbsorbedMean)} |`;

const HEAD =
  '| crew | win | Japan fell | timeout | cities left | boss HP left | clear time | score | SYNC avg | special ok/fallback/fail | assist acts | city dmg / shielded |\n|---|---|---|---|---|---|---|---|---|---|---|---|';

const started = Date.now();
const out: string[] = [];
out.push('# BALANCE REPORT — EARTH DEFENSE raid');
out.push('');
out.push(
  `Generated by \`pnpm simulate\`${quick ? ' --quick' : ''} on ${new Date().toISOString().slice(0, 10)} · config ${DEFAULT_GAME_CONFIG.version} #${configHash(DEFAULT_GAME_CONFIG)} · ${SEEDS} seeds per row.`,
);
out.push('');
out.push(
  'Simulated pilots act like the demo bots: request a mission, play the minigame with the given skill',
);
out.push(
  '(probability of a clean run), wait out the cooldown plus 1–4 s of "looking at the screen". They follow the',
);
out.push(
  'engine recommendation for targets. Real people will be slower at first and smarter later, so treat these',
);
out.push('numbers as a guide for venue playtests, not as a promise.');
out.push('');

out.push('## 1. Crew size (balanced seats, skill 0.65)');
out.push('');
out.push(HEAD);
for (const p of [1, 3, 5, 9, 16, 30, 60, 100]) out.push(row(`${p} pilots`, run(p, 'spread', 0.65)));
out.push('');

out.push('## 2. Role mix matters more than head count (skill 0.65)');
out.push('');
out.push(HEAD);
for (const p of [9, 30]) {
  out.push(row(`${p} · balanced`, run(p, 'spread', 0.65)));
  out.push(row(`${p} · all gunners`, run(p, 'gunners', 0.65)));
  out.push(row(`${p} · no router/engineer`, run(p, 'no-support', 0.65)));
}
out.push('');

out.push('## 3. Skill (9 pilots, balanced)');
out.push('');
out.push(HEAD);
for (const s of [0.3, 0.5, 0.65, 0.8, 0.95]) out.push(row(`skill ${s}`, run(9, 'spread', s)));
out.push('');

out.push('## Reading the table');
out.push('');
out.push(
  '- "city dmg / shielded": damage that reached cities vs. damage Fujin\'s shields absorbed, per raid. Large',
);
out.push(
  '  crews kill escorts inside the telegraph window, so most pressure comes from NULL CORE (see OPEN_ISSUES).',
);
out.push('');
out.push(
  "- Enemy and boss HP scale with active pilots (clamped), and each seat's effect is normalised by how many",
);
out.push(
  '  pilots are succeeding in it, so a big crowd does not win by mashing one seat (see section 2).',
);
out.push(
  '- Below 5 active pilots the assist AI fills empty seats; those raids are marked "assisted" and ranked separately.',
);
out.push(
  '- "special" is 神雷風陣: ACTIVATED needs three different pilots (gunner, guardian, router) inside the window,',
);
out.push('  SYNC ≥ 75 and a full reserve; otherwise the partial or failed branch plays.');
out.push('');
out.push(`_Runtime ${Math.round((Date.now() - started) / 1000)} s._`);
out.push('');

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, '../../../docs/BALANCE_REPORT.md');
writeFileSync(target, out.join('\n'));
console.log(out.join('\n'));
console.log(`\nwrote ${target}`);
