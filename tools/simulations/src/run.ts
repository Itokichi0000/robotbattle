/**
 * Balance simulator. Usage: pnpm simulate [--seasons 60] [--out docs/BALANCE_REPORT.md]
 * Writes a markdown report: team symmetry, round pacing vs crowd size, and how
 * often a smaller crowd still wins (pinch comeback).
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { GameConfig, TeamId } from '@sats-wars/shared';
import { DEFAULT_GAME_CONFIG, makeGameConfig } from '@sats-wars/shared';
import { carryOverHp } from '@sats-wars/game-engine';
import { aggregate, simulateSeason } from './simulate';

const args = process.argv.slice(2);
const arg = (name: string, def: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] ? args[i + 1]! : def;
};
const seasons = Number(arg('seasons', '60'));
const out = resolve(process.cwd(), arg('out', '../../docs/BALANCE_REPORT.md'));

const pct = (x: number, n: number) => `${((x / Math.max(1, n)) * 100).toFixed(1)}%`;
/**
 * Simulates the SECOND of two back-to-back seasons, like the venue's auto-loop:
 * its round-1 HP is carried over from the first (carryOverHp), so the numbers
 * reflect a crowd that has been playing for a while, not a cold start.
 */
const run = (players: Record<TeamId, number>, config: Partial<GameConfig> = {}, salt = 0) =>
  aggregate(
    Array.from({ length: seasons }, (_, i) => {
      const seed = 1000 + i * 7919 + players.RAIJIN * 31 + players.FUJIN + salt;
      const warm = simulateSeason({ playersPerTeam: players, seed, config });
      const base = makeGameConfig(config);
      const hpInitial = carryOverHp(base, warm.rounds[warm.rounds.length - 1]);
      return simulateSeason({ playersPerTeam: players, seed: seed + 1, config: { ...config, hpInitial } });
    }),
  );

const lines: string[] = [];
const started = Date.now();
lines.push('# SATS WARS ZAP BATTLE — Balance simulation report', '');
lines.push(
  `Generated by \`pnpm simulate\` (tools/simulations). Seasons per row: ${seasons}. Config: DEFAULT_GAME_CONFIG (${DEFAULT_GAME_CONFIG.version}).`,
  '',
  'Each row is the second of two back-to-back seasons (round-1 HP carried over, as the venue server does).',
  '',
  'Crowd model: each team has a steady number of people tapping. Each person taps with exponential gaps (personal mean 0.35–2.5 s, never faster than 0.26 s), buys 5/10/25 punches, and is replaced ~8 s after running out. Nobody taps between rounds. This is a **hypothesis check, not proof** — venue playtests decide.',
  '',
);

// 1. Pacing and symmetry with equal crowds.
lines.push('## 1. Equal crowds: round length and team symmetry', '');
lines.push(
  '| people/team | avg round (s) | p10–p90 (s) | KO rate | round wins R/F/draw | season wins R/F/draw | HP r1→r2→r4→r8 | punches/round/team | sats/season/team | season (s) |',
);
lines.push('|---|---|---|---|---|---|---|---|---|---|');
let worstSym = 0;
for (const n of [1, 3, 10, 30, 100]) {
  const a = run({ RAIJIN: n, FUJIN: n });
  const decisive = a.roundWins.RAIJIN + a.roundWins.FUJIN;
  worstSym = Math.max(worstSym, Math.abs(a.roundWins.RAIJIN - a.roundWins.FUJIN) / Math.max(1, decisive));
  const hp = [0, 1, 3, 7].map((i) => (a.hpByRound[i] ?? NaN).toFixed(0)).join('→');
  lines.push(
    `| ${n} | ${a.avgRoundSec.toFixed(1)} | ${a.p10RoundSec.toFixed(0)}–${a.p90RoundSec.toFixed(0)} | ${(a.koRate * 100).toFixed(0)}% | ${pct(a.roundWins.RAIJIN, a.rounds)}/${pct(a.roundWins.FUJIN, a.rounds)}/${pct(a.roundWins.DRAW, a.rounds)} | ${pct(a.seasonWins.RAIJIN, a.seasons)}/${pct(a.seasonWins.FUJIN, a.seasons)}/${pct(a.seasonWins.DRAW, a.seasons)} | ${hp} | ${a.avgPunchesPerRound.RAIJIN.toFixed(0)} | ${a.avgSatsPerSeason.RAIJIN.toFixed(0)} | ${a.avgSeasonSec.toFixed(0)} |`,
  );
}
lines.push(
  '',
  `Largest |RAIJIN−FUJIN| share of decisive rounds: **${(worstSym * 100).toFixed(1)}%** (sampling noise; the engine is mirror-symmetric, see engine.test.ts).`,
  '',
  'Reading: the robot HP follows the busier team\'s punch rate so a round lasts about `targetRoundSec` whether 2 or 200 people are tapping (HP may change at most ×`hpMaxChangeFactor` per round; round 1 starts from half the previous season\'s level).',
  '',
);

// 2. Uneven crowds: does the smaller team still get moments?
lines.push('## 2. Uneven crowds: underdog chances (pinch ×1.5 vs no pinch)', '');
lines.push('| crowd R vs F | pinch | FUJIN (smaller) round wins | FUJIN season wins | KO rate | avg round (s) |');
lines.push('|---|---|---|---|---|---|');
for (const [r, f] of [
  [10, 8],
  [10, 6],
  [30, 20],
  [3, 2],
] as const) {
  for (const pinch of [1.5, 1]) {
    const a = run({ RAIJIN: r, FUJIN: f }, { pinchMultiplier: pinch }, pinch === 1 ? 77 : 0);
    lines.push(
      `| ${r} vs ${f} | ×${pinch} | ${pct(a.roundWins.FUJIN, a.rounds)} | ${pct(a.seasonWins.FUJIN, a.seasons)} | ${(a.koRate * 100).toFixed(0)}% | ${a.avgRoundSec.toFixed(1)} |`,
    );
  }
}
lines.push(
  '',
  'The bigger crowd should usually win (that is the point: bring friends), but the smaller side must still take rounds sometimes so its fans keep tapping. Compare the ×1.5 rows with ×1 to see what the pinch rule buys.',
  '',
);

lines.push(`_Runtime: ${((Date.now() - started) / 1000).toFixed(0)} s._`, '');
writeFileSync(out, lines.join('\n'));
console.log(lines.join('\n'));
console.log(`\nwrote ${out}`);
