/**
 * Balance simulator. Usage: pnpm simulate [--matches 400] [--out docs/BALANCE_REPORT.md]
 * Writes a markdown report with fairness (team symmetry), pacing and strategy matchups.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { TeamId } from '@sats-wars/shared';
import { DEFAULT_GAME_CONFIG } from '@sats-wars/shared';
import { STRATEGY_NAMES, type StrategyName } from '@sats-wars/game-engine';
import { aggregate, simulateMatch } from './simulate';

const args = process.argv.slice(2);
const arg = (name: string, def: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] ? args[i + 1]! : def;
};
const matches = Number(arg('matches', '200'));
const out = resolve(process.cwd(), arg('out', '../../docs/BALANCE_REPORT.md'));

const pct = (x: number, n: number) => `${((x / n) * 100).toFixed(1)}%`;
const lines: string[] = [];
const started = Date.now();
lines.push('# SATS WARS — Balance simulation report', '');
lines.push(
  `Generated by \`pnpm simulate\` (tools/simulations). Matches per cell: ${matches}. Config: DEFAULT_GAME_CONFIG (${DEFAULT_GAME_CONFIG.version}).`,
  '',
);
lines.push(
  'Each simulated player joins (30% join late, before 180s) and spends 3 AP at random moments, choosing actions with a heuristic strategy against the live state. Numbers are a **balance hypothesis check**, not proof — playtests decide.',
  '',
);

// 1. Fairness: identical strategies, identical team sizes.
lines.push('## 1. Team symmetry (same strategy, same team size)', '');
lines.push(
  '| players/team | strategy | RAIJIN win | FUJIN win | draw | KO rate | avg end (s) | avg HP left R/F | avg regions R/F | rejected actions |',
);
lines.push('|---|---|---|---|---|---|---|---|---|---|');
let fairnessWorst = 0;
for (const players of [3, 10, 30, 100]) {
  for (const strategy of ['balanced', 'random'] as StrategyName[]) {
    const results = Array.from({ length: matches }, (_, i) =>
      simulateMatch({
        playersPerTeam: { RAIJIN: players, FUJIN: players },
        strategy: { RAIJIN: strategy, FUJIN: strategy },
        seed: 1000 + i * 7919 + players,
      }),
    );
    const a = aggregate(results);
    const decisive = a.raijinWins + a.fujinWins;
    if (decisive > 0)
      fairnessWorst = Math.max(fairnessWorst, Math.abs(a.raijinWins - a.fujinWins) / decisive);
    lines.push(
      `| ${players} | ${strategy} | ${pct(a.raijinWins, a.n)} | ${pct(a.fujinWins, a.n)} | ${pct(a.draws, a.n)} | ${(a.koRate * 100).toFixed(1)}% | ${a.avgEndSec.toFixed(0)} | ${a.avgHpLeft.RAIJIN.toFixed(1)}/${a.avgHpLeft.FUJIN.toFixed(1)} | ${a.avgRegions.RAIJIN.toFixed(2)}/${a.avgRegions.FUJIN.toFixed(2)} | ${(a.rejectRate * 100).toFixed(1)}% |`,
    );
  }
}
lines.push(
  '',
  `Largest |RAIJIN−FUJIN| share of decisive games: **${(fairnessWorst * 100).toFixed(1)}%** (sampling noise expected at this n; the engine is exactly mirror-symmetric, see engine.test.ts "fairness").`,
  '',
);

// 2. Strategy matchups (row strategy plays RAIJIN, column strategy plays FUJIN, then swapped and averaged).
lines.push(
  '## 2. Strategy matchups (10 vs 10, row win rate vs column, sides swapped and averaged)',
  '',
);
lines.push(`| row \\ col | ${STRATEGY_NAMES.join(' | ')} |`);
lines.push(`|---|${STRATEGY_NAMES.map(() => '---').join('|')}|`);
const dominance: Record<string, number> = {};
for (const row of STRATEGY_NAMES) {
  const cells: string[] = [];
  let sum = 0;
  for (const col of STRATEGY_NAMES) {
    let wins = 0;
    let total = 0;
    for (const [rTeam, cTeam] of [
      ['RAIJIN', 'FUJIN'],
      ['FUJIN', 'RAIJIN'],
    ] as Array<[TeamId, TeamId]>) {
      for (let i = 0; i < matches / 2; i++) {
        const strategy = { [rTeam]: row, [cTeam]: col } as Record<TeamId, StrategyName>;
        const r = simulateMatch({
          playersPerTeam: { RAIJIN: 10, FUJIN: 10 },
          strategy,
          seed: 50_000 + i * 104729 + row.length * 31 + col.length,
        });
        total++;
        if (r.winner === rTeam) wins++;
        else if (r.winner === null) wins += 0.5;
      }
    }
    sum += wins / total;
    cells.push(`${((wins / total) * 100).toFixed(0)}%`);
  }
  dominance[row] = sum / STRATEGY_NAMES.length;
  lines.push(`| **${row}** | ${cells.join(' | ')} |`);
}
lines.push('', 'Average score per strategy across all opponents (50% = neutral):', '');
for (const [k, v] of Object.entries(dominance).sort((a, b) => b[1] - a[1]))
  lines.push(`- ${k}: ${(v * 100).toFixed(1)}%`);

// 3. Imbalanced teams.
lines.push('', '## 3. Uneven team sizes (balanced strategy)', '');
lines.push(
  '| RAIJIN players | FUJIN players | RAIJIN win | FUJIN win | draw |',
  '|---|---|---|---|---|',
);
for (const [r, f] of [
  [10, 11],
  [10, 12],
  [10, 15],
  [5, 10],
] as Array<[number, number]>) {
  const a = aggregate(
    Array.from({ length: matches }, (_, i) =>
      simulateMatch({
        playersPerTeam: { RAIJIN: r, FUJIN: f },
        strategy: { RAIJIN: 'balanced', FUJIN: 'balanced' },
        seed: 9_000 + i * 31,
      }),
    ),
  );
  lines.push(
    `| ${r} | ${f} | ${pct(a.raijinWins, a.n)} | ${pct(a.fujinWins, a.n)} | ${pct(a.draws, a.n)} |`,
  );
}
lines.push(
  '',
  '## Observations',
  '',
  '_See docs/DECISION_LOG.md for the tuning decisions taken from this report._',
  '',
);
lines.push(`Runtime: ${((Date.now() - started) / 1000).toFixed(1)}s`);
writeFileSync(out, `${lines.join('\n')}\n`);
console.log(lines.join('\n'));
console.log(`\nWrote ${out}`);
