/**
 * Balance simulator. Usage: pnpm simulate [--campaigns 200] [--out docs/BALANCE_REPORT.md]
 * Writes a markdown report: how long a campaign lasts (waves, paid moves, sats),
 * how much choosing well matters, and how sensitive it is to actionsPerTurn.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { GameConfig } from '@sats-wars/shared';
import { DEFAULT_GAME_CONFIG } from '@sats-wars/shared';
import { aggregate, simulateCampaign } from './simulate';

const args = process.argv.slice(2);
const arg = (name: string, def: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] ? args[i + 1]! : def;
};
const campaigns = Number(arg('campaigns', '200'));
const out = resolve(process.cwd(), arg('out', '../../docs/BALANCE_REPORT.md'));

const run = (autoShare: number, config: Partial<GameConfig> = {}) =>
  aggregate(Array.from({ length: campaigns }, (_, i) => simulateCampaign({ seed: 1000 + i * 7919, autoShare, config })));

const row = (label: string, a: ReturnType<typeof aggregate>) =>
  `| ${label} | ${a.waveMean.toFixed(1)} | ${a.waveP10}–${a.waveP50}–${a.waveP90} | ${a.actionsMean.toFixed(0)} | ${a.satsMean.toFixed(0)} | ${a.regionsLostMean.toFixed(1)} | ${a.liberatedMean.toFixed(1)} | ${a.combosMean.toFixed(1)} | ${(a.fellShare * 100).toFixed(0)}% |`;
const HEAD = [
  '| crowd | mean wave reached | wave p10–p50–p90 | paid moves | sats | regions captured | liberated | combos | ended by 日本陥落 |',
  '|---|---|---|---|---|---|---|---|---|',
];

const lines: string[] = [];
const started = Date.now();
lines.push('# SATS WARS EARTH DEFENSE — Balance simulation report', '');
lines.push(
  `Generated by \`pnpm simulate\` (tools/simulations). Campaigns per row: ${campaigns}. Config: DEFAULT_GAME_CONFIG (${DEFAULT_GAME_CONFIG.version}).`,
  '',
  'The game has no clock: it only advances when someone pays for a move, so crowd size changes how *fast* a campaign plays out, never how it ends. A campaign is therefore simulated as a sequence of paid moves.',
  '',
  'Crowd model: each move is either the おすすめ button (`AUTO`, chosen by the engine) or a casual player\'s own pick (random region with aliens, ⚡ 60% / 🌀 40%, 🛡 15% on a random region, 💥 half the time it is ready). A refused casual pick is free and the person then presses おすすめ. This is a **hypothesis check, not proof** — venue playtests decide.',
  '',
);

lines.push('## 1. How long does a campaign last?', '');
lines.push(...HEAD);
for (const [label, share] of [
  ['everyone presses おすすめ', 1],
  ['60% おすすめ / 40% own picks', 0.6],
  ['20% おすすめ / 80% own picks', 0.2],
  ['only own picks (random)', 0],
] as const) {
  lines.push(row(label, run(share)));
}
lines.push(
  '',
  `Reading: ${DEFAULT_GAME_CONFIG.actionCostSats} sats per move. "sats" is what the whole venue spends on one campaign, start to 日本陥落. Good choices buy a few more waves; random play still lasts long enough to feel like a fight.`,
  '',
);

lines.push('## 2. actionsPerTurn (moves between alien turns)', '');
lines.push(...HEAD);
for (const apt of [6, 8, 10, 12]) {
  lines.push(row(`actionsPerTurn=${apt} (60% おすすめ)`, run(0.6, { actionsPerTurn: apt })));
}
lines.push(
  '',
  'Fewer moves per turn = the aliens act more often per sat = shorter, tenser campaigns. Default is 8.',
  '',
);

lines.push(`_Runtime: ${((Date.now() - started) / 1000).toFixed(0)} s._`, '');
writeFileSync(out, lines.join('\n'));
console.log(lines.join('\n'));
console.log(`\nwrote ${out}`);
